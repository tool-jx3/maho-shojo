"""
以網站現行翻譯（docs/src/content/docs/rules/*.md + glossary.json）重建 tsv/ 四份扮演書表。
輸出與原檔完全相同的欄位與列結構：
  - 列分隔 CRLF、儲存格內換行為單一 CR（Google Sheets TSV 匯出格式）
  - 檔尾不加換行
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")


QUOTED = os.environ.get("TSV_QUOTED") == "1"


def _cell(c):
    """QUOTED=0：儲存格內換行輸出裸 CR（Google Sheets 原始匯出格式）。
    QUOTED=1：含換行／定位／引號的儲存格以 "" 包覆，內部換行改為 CRLF（RFC 4180）。"""
    if not QUOTED:
        return c.replace("\n", "\r")
    if "\n" in c or "\t" in c or '"' in c:
        return '"' + c.replace('"', '""').replace("\n", "\r\n") + '"'
    return c


def write_tsv(out_dir, filename, header, rows, ncol):
    os.makedirs(out_dir, exist_ok=True)
    lines = []
    for r in [header] + rows:
        assert len(r) == ncol, (filename, len(r), ncol)
        lines.append("\t".join(_cell(c) for c in r))
    path = os.path.join(out_dir, filename)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write("\r\n".join(lines))
    print("wrote", path, "rows=%d cols=%d quoted=%s" % (len(rows), ncol, QUOTED))


def grid(nrow, ncol):
    return [["" for _ in range(ncol)] for _ in range(nrow)]


def fill(rows, col_start, data):
    """data: list of tuples，依序填入從 col_start 開始的欄位。"""
    for i, tup in enumerate(data):
        for j, v in enumerate(tup):
            rows[i][col_start + j] = v


